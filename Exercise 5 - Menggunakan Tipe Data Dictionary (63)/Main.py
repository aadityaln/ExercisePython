## Program Untuk Menyimpan dan Menampilkan Biodara Menggunakan Tipe Data Dictionary

# mendefinisikan dictionary untuk biodata
biodata = {
    "nama": "ochaa",
    "umur": "20",
    "pekerjaan": "mahasiswa"
}

# menampilkan informasi biodata
print("Nama :", biodata["nama"])
print("Umur :", biodata["umur"])
print("Pekerjaan :", biodata["pekerjaan"])