## Menghitung luas Bangun Datar

# variabel untuk menyimpan nilai
sisiPersegi = 5
jariJari    = 7

# menghitung luas persegi
luasPersegi = sisiPersegi * sisiPersegi
print ("Luas persegi dengan sisi : ", sisiPersegi, "adalah :", luasPersegi)

# menghitung luas lingkaran
pi = 3.14
luasLingkaran = pi * jariJari * jariJari
print ("Luas lingkaran dengan jari-jari :", jariJari, "adalah :", luasLingkaran)

pi = 22 / 7
luasLingkaran = pi * jariJari * jariJari
print ("Luas lingkaran dengan jari-jari :", jariJari, "adalah :", luasLingkaran)